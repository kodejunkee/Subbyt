export const getCurrencySearchTerms = (currencyCode: string): string => {
  const data = CURRENCY_MAP[currencyCode];
  if (!data) return currencyCode.toLowerCase();
  
  return [currencyCode, data.name, ...data.searchTerms]
    .join(" ")
    .toLowerCase();
};

export const getCurrencyName = (currencyCode: string): string => {
  return CURRENCY_MAP[currencyCode]?.name || currencyCode;
};
